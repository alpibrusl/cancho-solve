#!/usr/bin/env python3
"""Writes lib/model/layout.cho: the cells of the two state slices (`ints`, `fl`) as functions, so offsets are computed once and cannot overlap.
`python3 scripts/gen_layout.py --check` fails if the file on disk is not what this prints."""
import sys

LIMITS = dict(maxv=16384, maxsym=4096, maxrows=16384, maxnz=1048576, maxpool=1048576, maxlv=8)

HEADER = ["pos", "rule", "at", "nvars", "nnz", "ncons", "nints", "sense", "obj_nnz", "nsym", "npool", "nlv", "ntouched",
          "obj_ns", "obj_ne", "numeric", "steps", "obj_terms", "nrows_terms", "lab_s", "lab_e"]
HEADER_SIZE = 32
# (name, size name) -- arrays of ints, in order
INTS = [("sym_s", "maxsym"), ("sym_e", "maxsym"), ("sym_class", "maxsym"), ("sym_kind", "maxsym"), ("sym_base", "maxsym"),
        ("sym_size", "maxsym"), ("sym_nd", "maxsym"), ("sym_lo0", "maxsym"), ("sym_n0", "maxsym"), ("sym_lo1", "maxsym"),
        ("sym_n1", "maxsym"), ("lv_s", "maxlv"), ("lv_e", "maxlv"), ("touched", "maxv"), ("flag", "maxv"),
        ("row_start", "maxrows+1"), ("row_sense", "maxrows"), ("row_ns", "maxrows"), ("row_ne", "maxrows"), ("row_nidx", "maxrows"),
        ("row_i0", "maxrows"), ("row_i1", "maxrows"), ("row_i2", "maxrows"), ("row_i3", "maxrows"), ("term_col", "maxnz"),
        ("obj_col", "maxv")]
FLS = [("sym_lo", "maxsym"), ("sym_hi", "maxsym"), ("pool", "maxpool"), ("lv_val", "maxlv"), ("acc", "maxv"), ("const", "1"),
       ("row_rhs", "maxrows"), ("term_coef", "maxnz"), ("obj_coef", "maxv"), ("obj_const", "1")]

def size(expr):
    return sum(LIMITS.get(p, None) if p in LIMITS else int(p) for p in expr.split("+"))

def render():
    out = ["edition 7;", "", "module solve.layout;", "",
           "// GENERATED by scripts/gen_layout.py -- do not edit. The cells of the state slices of the model checker (docs/design.md section 12).", ""]
    for k, v in LIMITS.items():
        out += [f"pub fn {k}() -> [] int {{", f"    return {v};", "}", ""]
    for i, h in enumerate(HEADER):
        out += [f"pub fn h_{h}() -> [] int {{", f"    return {i};", "}", ""]
    at = HEADER_SIZE
    for name, sz in INTS:
        out += [f"pub fn {name}(k: int) -> [] int {{", f"    return {at} + k;", "}", ""]
        at += size(sz)
    out += ["pub fn ints_len() -> [] int {", f"    return {at};", "}", ""]
    at = 0
    for name, sz in FLS:
        out += [f"pub fn {name}(k: int) -> [] int {{", f"    return {at} + k;", "}", ""]
        at += size(sz)
    out += ["pub fn fl_len() -> [] int {", f"    return {at};", "}", ""]
    return "\n".join(out)

if __name__ == "__main__":
    text = render()
    path = "lib/model/layout.cho"
    if "--check" in sys.argv:
        sys.exit(0 if open(path).read() == text else (print("layout.cho is not what gen_layout.py prints") or 1))
    open(path, "w").write(text)
